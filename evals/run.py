"""Run every scenario and write eval_results.md / eval_table.csv from the actual run.
Usage: python -m evals.run [--out evals/results]"""
from __future__ import annotations

import argparse
import csv
import sys
import tempfile
import time
import traceback
from pathlib import Path

from evals import harness
from evals.scenarios import SCENARIOS


def run_one(sc, workdir: Path) -> dict:
    t0 = time.perf_counter()
    try:
        harness.ACTIVE.clear()
        actual, checks, notes = sc.fn(workdir)
        inv = {}
        for h in harness.ACTIVE:
            for name, ok in h.invariants():
                inv[name] = inv.get(name, True) and ok
        checks = list(checks) + [("invariant: " + n, ok) for n, ok in inv.items()]
        passed = all(ok for _, ok in checks)
        failed = [n for n, ok in checks if not ok]
    except Exception as e:  # a crashing scenario is a failing scenario
        actual, checks, notes, passed = f"error: {type(e).__name__}: {e}", [], traceback.format_exc(limit=2), False
        failed = ["scenario raised"]
    return {"scenario": sc.name, "category": sc.category, "expected": sc.expected, "actual": actual,
            "result": "PASS" if passed else "FAIL", "checks": len(checks),
            "notes": ("failed: " + "; ".join(failed)) if failed else (notes or "; ".join(n for n, _ in checks)),
            "ms": round((time.perf_counter() - t0) * 1000, 1)}


def run_all(out_dir: Path | None = None) -> list[dict]:
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for sc in SCENARIOS:
            wd = Path(tmp) / sc.name
            wd.mkdir()
            rows.append(run_one(sc, wd))
    if out_dir:
        write(rows, Path(out_dir))
    return rows


def write(rows: list[dict], out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    cols = ["scenario", "category", "expected", "actual", "result", "notes"]
    with open(out / "eval_table.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols + ["checks", "ms"])
        w.writeheader()
        w.writerows(rows)
    n_pass = sum(r["result"] == "PASS" for r in rows)
    esc = lambda s: str(s).replace("|", "\\|").replace("\n", " ")
    lines = ["# Eval results", "", f"Generated by `python -m evals.run` (also run by pytest). "
             f"{n_pass}/{len(rows)} scenarios passed; every scenario also checks the global invariants "
             "(no booking without a matching user-granted approval, at most one booking per approval, no duplicate slots).",
             "", "| # | scenario | category | expected | actual | pass/fail | notes |", "|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        lines.append(f"| {i} | {r['scenario']} | {r['category']} | {esc(r['expected'])} | {esc(r['actual'])} | "
                     f"{r['result']} | {esc(r['notes'])} |")
    (out / "eval_results.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="evals/results")
    rows = run_all(Path(ap.parse_args().out))
    for r in rows:
        print(f"{r['result']}  {r['scenario']:40s} {r['actual'][:90]}")
    print(f"{sum(r['result'] == 'PASS' for r in rows)}/{len(rows)} passed")
    sys.exit(0 if all(r["result"] == "PASS" for r in rows) else 1)
